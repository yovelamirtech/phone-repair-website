/**
 * Downloads the stock photos listed in scripts/images.sources.json, converts them to WebP
 * in several widths, and writes:
 *   public/images/photos/<name>-<width>.webp
 *   src/data/images.generated.json   (which images exist + their aspect ratio)
 *   public/images/CREDITS.md          (source, author, license for every photo)
 *
 * Images that fail to download are skipped; the site shows a clean light background instead.
 * Run locally: npm run images:fetch
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { images, widths } = JSON.parse(readFileSync(join(root, 'scripts/images.sources.json'), 'utf8'));
const outDir = join(root, 'public/images/photos');
mkdirSync(outDir, { recursive: true });

const manifest = {};
const credits = [];
const maxWidth = Math.max(...widths);

for (const img of images) {
  try {
    // ask the CDN for a reasonably sized JPEG (Unsplash supports w/q/fm params)
    const url = `${img.src}?w=${maxWidth}&q=85&fm=jpg&fit=max`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    const meta = await sharp(buf).metadata();
    const ratio = (meta.width ?? 1) / (meta.height ?? 1);
    for (const w of widths) {
      await sharp(buf)
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 74 })
        .toFile(join(outDir, `${img.name}-${w}.webp`));
    }
    manifest[img.name] = { width: meta.width, height: meta.height, ratio: Number(ratio.toFixed(4)) };
    credits.push(img);
    console.log('ok  ', img.name);
  } catch (err) {
    console.warn('skip', img.name, String(err));
  }
}

writeFileSync(join(root, 'src/data/images.generated.json'), JSON.stringify({ widths, images: manifest }, null, 2) + '\n');

const lines = [
  '# Image credits',
  '',
  'All photos are TEMPORARY placeholders from [Unsplash](https://unsplash.com), used under the',
  '[Unsplash License](https://unsplash.com/license) (free for commercial use, attribution appreciated).',
  'Replace them with real photos of the lab before going live.',
  '',
  'Brand graphics: `logo.svg` and the icons in `/icons` are generated by `scripts/generate-brand-assets.mjs`.',
  '`whatsapp-white.svg` is the WhatsApp glyph from [Simple Icons](https://simpleicons.org) (CC0), used per',
  "[WhatsApp's brand guidelines](https://www.whatsappbrand.com/).",
  '',
  '| File | Source | Author | License |',
  '| --- | --- | --- | --- |',
  ...credits.map(
    (c) => `| \`photos/${c.name}-*.webp\` | [Unsplash](${c.page}) | [${c.author}](${c.authorUrl}) | Unsplash License |`,
  ),
  '',
];
writeFileSync(join(root, 'public/images/CREDITS.md'), lines.join('\n'));
console.log(`Done: ${credits.length}/${images.length} images`);
